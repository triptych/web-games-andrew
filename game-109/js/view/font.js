export const CHAR_W = 6, CHAR_H = 7;            // advance and height at scale 1
const cache = new Map();

function glyph(ch, color) {
    const key = ch + color;
    let c = cache.get(key);
    if (c) return c;
    const rows = (GLYPHS[ch] || GLYPHS['?']).split('/');
    c = document.createElement('canvas');
    c.width = 5; c.height = 7;
    const g = c.getContext('2d');
    g.fillStyle = color;
    rows.forEach((r, y) => { for (let x = 0; x < 5; x++) if (r[x] === '1') g.fillRect(x, y, 1, 1); });
    cache.set(key, c);
    return c;
}

export const textWidth = (s, scale = 1) => Math.max(0, s.length * CHAR_W - 1) * scale;

/**
 * Draw `text` with its left edge (align 'l'), centre ('c') or right edge ('r') at x, top at y.
 * shadow: a colour for a one-pixel drop shadow (scaled).
 */
export function drawText(g, text, x, y, color = '#ffffff', { scale = 1, align = 'l', shadow = null } = {}) {
    const s = String(text).toUpperCase(), w = textWidth(s, scale);
    let px = Math.round(align === 'c' ? x - w / 2 : align === 'r' ? x - w : x);
    const py = Math.round(y);
    for (const ch of s) {
        if (shadow) g.drawImage(glyph(ch, shadow), px + scale, py + scale, 5 * scale, 7 * scale);
        g.drawImage(glyph(ch, color), px, py, 5 * scale, 7 * scale);
        px += CHAR_W * scale;
    }
}
