// Interiors and dungeons, drawn as text. js/sim/worldgen.js builds them into tile maps.
//
//   #  wall          .  floor        ,  rug / carpet     :  second floor (path)
//   ~  water         =  bridge       ^  pit              X  the way out
//   @  where you arrive               e  a foe            E  the guardian
//   c  a chest (contents from `chests`, in reading order)   k  a chest holding the dungeon key
//   D  a locked door (dungeon key)   >  stairs (see `stairs`)
//   T thorns  F fog  B boulder  S stream  t mouse door  V sprout  G ghost gate  R rune seal
//   C chasm   *  star seal  d  pitch dark
//   s shelf  b bed  h hearth  q table  K counter  o statue  | pillar  l lamp  L lectern
//   Q the Returns Cart  r barrel  x crate  p plant  z loose pages  M mushroom  Y tree  n kiln
//   w well  u telescope  P pedestal  a anvil

