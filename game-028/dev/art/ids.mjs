// Writes prompts_ids.py (the sheet cell names) for export.py, so the names live in one place: prompts.mjs.
import fs from 'node:fs';
import { SHEETS, ITEM_SHEET } from './prompts.mjs';
const sheets = Object.fromEntries(Object.entries(SHEETS).map(([k, v]) => [k, v[1]]));
fs.writeFileSync(new URL('./prompts_ids.py', import.meta.url), `# generated by ids.mjs from prompts.mjs\nSHEETS = ${JSON.stringify(sheets)}\nITEMS = ${JSON.stringify(ITEM_SHEET[1])}\n`);
