const GLYPHS = {};
for (const [ch, rows] of Object.entries(G)) GLYPHS[ch] = rows.split(' ').map((r) => [...r].map((c) => c === '1'));

export const CW = 6;   // advance per character, UI px
export const CH = 7;

const strips = new Map();
function strip(color) {
    let c = strips.get(color);
    if (c) return c;
    const chars = Object.keys(GLYPHS);
    c = document.createElement('canvas');
    c.width = chars.length * CW; c.height = CH;
    const g = c.getContext('2d');
    g.fillStyle = color;
    chars.forEach((ch, i) => {
        GLYPHS[ch].forEach((row, y) => row.forEach((on, x) => { if (on) g.fillRect(i * CW + x, y, 1, 1); }));
    });
    c.index = Object.fromEntries(chars.map((ch, i) => [ch, i]));
    strips.set(color, c);
    return c;
}

export const textWidth = (str, scale = 1) => (String(str).length ? String(str).length * CW * scale - scale : 0);

/** Draw one run of text, one colour. */
export function drawRaw(ctx, str, x, y, color, scale = 1) {
    const s = strip(color);
    ctx.imageSmoothingEnabled = false;
    for (let i = 0; i < str.length; i++) {
        const k = s.index[str[i]];
        if (k === undefined || str[i] === ' ') continue;
        ctx.drawImage(s, k * CW, 0, 5, CH, x + i * CW * scale, y, 5 * scale, CH * scale);
    }
}
