"""WanderQuest audio pipeline: raw ElevenLabs downloads -> game-085/audio/ and js/audio-files.js (needs ffmpeg).

    python3 -I game-085/dev/audio/process.py RAW_DIR

RAW_DIR holds music-*.mp3, amb-*.mp3, loop-drums.mp3 and sfx-*.mp3 as downloaded.

- Music and ambience are made to loop: the first XF seconds are cross-faded under the last XF (equal power) and the
  head is dropped, so the end runs straight back into the start. Loudness-normalised; music 96 kbps stereo,
  ambience 64 kbps mono.
- Effects are trimmed of silence at both ends, capped (ElevenLabs ignores short durations now and then), faded out,
  peak-normalised to -1 dBFS and saved at 80 kbps mono.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GAME = HERE.parent.parent
OUT = GAME / 'audio'
CAP = {'warden': 3.6, 'win': 2.4, 'lose': 2.4, 'levelup': 2.4, 'camp': 2.4, 'arrive': 2.4}


def ff(*args):
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', *args], check=True)


def duration(path):
    out = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(path)], capture_output=True, text=True).stdout
    return float(out.strip())


def peak_db(path):
    err = subprocess.run(['ffmpeg', '-hide_banner', '-i', str(path), '-af', 'volumedetect', '-f', 'null', '-'], capture_output=True, text=True).stderr
    m = re.search(r'max_volume: (-?[0-9.]+) dB', err)
    return float(m.group(1)) if m else 0.0


def loop(src, dst, xf, rate, channels, lufs):
    d = duration(src)
    # [xf, d) with its last xf seconds cross-faded into [0, xf)
    ff('-i', str(src), '-i', str(src), '-filter_complex',
       f'[0:a]atrim=start={xf},asetpts=PTS-STARTPTS[body];[1:a]atrim=0:{xf},asetpts=PTS-STARTPTS[head];'
       f'[body][head]acrossfade=d={xf}:c1=qsin:c2=qsin,loudnorm=I={lufs}:TP=-1.5[out]',
       '-map', '[out]', '-ac', str(channels), '-ar', '44100', '-b:a', rate, str(dst))
    return d - xf


def main(raw):
    raw = Path(raw)
    for sub in ('music', 'amb', 'sfx'):
        (OUT / sub).mkdir(parents=True, exist_ok=True)
    files = {'music': [], 'amb': [], 'sfx': []}
    for f in sorted(raw.glob('music-*.mp3')):
        name = f.stem.replace('music-', '')
        n = loop(f, OUT / 'music' / f'{name}.mp3', 3.0, '96k', 2, -17)
        files['music'].append(name)
        print('music', name, round(n, 1), 's')
    for f in sorted(raw.glob('amb-*.mp3')) + [raw / 'loop-drums.mp3']:
        if not f.exists():
            continue
        name = f.stem.replace('amb-', '').replace('loop-', '')
        n = loop(f, OUT / 'amb' / f'{name}.mp3', 0.4 if name == 'drums' else 2.0, '64k', 1, -20)
        files['amb'].append(name)
        print('loop', name, round(n, 1), 's')
    tmp = OUT / '_tmp.wav'
    for f in sorted(raw.glob('sfx-*.mp3')):
        name = f.stem.replace('sfx-', '')
        cap = CAP.get(name, 1.8)
        # normalise first (one clip came back peaking at -30 dB), then trim what is quiet relative to the peak
        gain = -1.0 - peak_db(f)
        ff('-i', str(f), '-af',
           f'volume={gain:.2f}dB,'
           'silenceremove=start_periods=1:start_threshold=-42dB,areverse,silenceremove=start_periods=1:start_threshold=-42dB,areverse',
           '-ac', '1', '-ar', '44100', str(tmp))
        d = min(cap, duration(tmp))
        ff('-i', str(tmp), '-af', f'atrim=0:{d:.3f},afade=t=out:st={max(0.02, d - 0.1):.3f}:d=0.1', '-b:a', '80k', str(OUT / 'sfx' / f'{name}.mp3'))
        files['sfx'].append(name)
        print('sfx', name, round(duration(OUT / 'sfx' / f'{name}.mp3'), 2), 's')
    tmp.unlink(missing_ok=True)
    js = '// Generated by dev/audio/process.py: every clip in audio/, so the game never requests one that isn\'t there.\n'
    js += 'export const AUDIO_FILES = ' + json.dumps(files) + ';\n'
    (GAME / 'js' / 'audio-files.js').write_text(js)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'raw')
