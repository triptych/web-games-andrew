// A row of n trees from (x1,z1) to (x2,z2), jittered deterministically.
function row(x1, z1, x2, z2, n, jit = 2, s = 1, style, seed = 1) {
    const out = [];
    for (let i = 0; i < n; i++) {
        const t = n === 1 ? 0.5 : i / (n - 1);
        const jx = (hash2(i, seed, 11) - 0.5) * 2 * jit, jz = (hash2(i, seed, 23) - 0.5) * 2 * jit;
        const sc = s * (0.85 + hash2(i, seed, 37) * 0.35);
        out.push(style ? [x1 + (x2 - x1) * t + jx, z1 + (z2 - z1) * t + jz, sc, style] : [x1 + (x2 - x1) * t + jx, z1 + (z2 - z1) * t + jz, sc]);
    }
    return out;
}
// A scatter of n trees in an ellipse.
function grove(cx, cz, rx, rz, n, s = 1, style, seed = 7) {
    const out = [];
    for (let i = 0; i < n; i++) {
        const a = hash2(i, seed, 3) * Math.PI * 2, r = Math.sqrt(hash2(i, seed, 5));
        const sc = s * (0.8 + hash2(i, seed, 9) * 0.45);
        const p = [cx + Math.sin(a) * rx * r, cz + Math.cos(a) * rz * r, sc];
        if (style) p.push(style);
        out.push(p);
    }
    return out;
}
const circle = (cx, cz, r, n, a0 = 0) => Array.from({ length: n }, (_, i) => { const a = a0 + (i / n) * Math.PI * 2; return [cx + Math.sin(a) * r, cz + Math.cos(a) * r]; });

