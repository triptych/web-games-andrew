/**
 * add-meta.mjs — give every game's index.html link-preview metadata.
 *
 * Writes a <meta> block (description, canonical, Open Graph, Twitter card)
 * right after each game's </title>, so a shared game link unfurls with a
 * title, a blurb and a picture. The picture is garden/img/games/<game>.jpg,
 * made by dev/screenshots.mjs. Titles and blurbs come from js/gamedata.js; a
 * description <meta> the game already has is kept and reused.
 *
 * Safe to re-run: the block sits between "share-meta" comments and is
 * replaced in place.
 *
 *   node dev/add-meta.mjs
 *   ONLY=game-001 node dev/add-meta.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SITE = 'https://triptych.github.io/web-games-andrew';
const START = '<!-- share-meta:start (generated by dev/add-meta.mjs) -->';
const END = '<!-- share-meta:end -->';
const only = process.env.ONLY ? process.env.ONLY.split(',') : null;

const { default: games } = await import(pathToFileURL(path.join(ROOT, 'js', 'gamedata.js')).href);

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const unesc = (s) => s.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

function excerpt(text, n) {
    if (text.length <= n) return text;
    const cut = text.slice(0, n);
    return cut.slice(0, Math.max(cut.lastIndexOf(' '), n - 30)).replace(/[,;:\s—-]+$/, '') + '…';
}

let changed = 0;
for (const game of games) {
    if (only && !only.includes(game.id)) continue;
    const file = path.join(ROOT, game.folder, 'index.html');
    if (!fs.existsSync(file)) { console.log(`skip ${game.id}: no index.html`); continue; }
    let html = fs.readFileSync(file, 'utf8');

    // drop a previous run's block, then see what the page already says for itself
    html = html.replace(new RegExp(`[ \\t]*${START.replace(/[()/.]/g, '\\$&')}[\\s\\S]*?${END}\\n?`), '');
    const existing = html.match(/<meta\s+name=["']description["']\s+content=["']([^"']*)["']/i);
    const blurb = excerpt(existing ? unesc(existing[1]) : game.description, 200);

    const url = `${SITE}/${game.folder}/`;
    const image = `${SITE}/garden/img/games/${game.id}.jpg`;
    const alt = `Screenshot of ${game.title}`;
    const lines = [
        START,
        ...(existing ? [] : [`<meta name="description" content="${esc(blurb)}">`]),
        `<link rel="canonical" href="${url}">`,
        `<meta property="og:type" content="website">`,
        `<meta property="og:site_name" content="Andrew Wooldridge's Games">`,
        `<meta property="og:title" content="${esc(game.title)}">`,
        `<meta property="og:description" content="${esc(blurb)}">`,
        `<meta property="og:url" content="${url}">`,
        `<meta property="og:image" content="${image}">`,
        `<meta property="og:image:secure_url" content="${image}">`,
        `<meta property="og:image:type" content="image/jpeg">`,
        `<meta property="og:image:width" content="1200">`,
        `<meta property="og:image:height" content="630">`,
        `<meta property="og:image:alt" content="${esc(alt)}">`,
        `<meta name="twitter:card" content="summary_large_image">`,
        `<meta name="twitter:title" content="${esc(game.title)}">`,
        `<meta name="twitter:description" content="${esc(blurb)}">`,
        `<meta name="twitter:image" content="${image}">`,
        `<meta name="twitter:image:alt" content="${esc(alt)}">`,
        END,
    ];

    const m = html.match(/([ \t]*)<title>[\s\S]*?<\/title>[ \t]*\r?\n/i);
    if (!m) { console.log(`skip ${game.id}: no <title>`); continue; }
    const indent = m[1];
    const block = lines.map((l) => indent + l).join('\n') + '\n';
    html = html.replace(m[0], m[0] + block);
    fs.writeFileSync(file, html);
    changed++;
}
console.log(`${changed} game pages updated`);
