#!/usr/bin/env python3
"""Raw ElevenLabs generations -> game-030/audio/ and js/audio-files.js.   python3 -I dev/audio/process.py RAW_DIR

RAW_DIR holds the downloaded mp3s: <sfx name>.mp3 for each effect, and take-<speaker>.mp3 for each voice take
(see takes.json, written by voices.mjs). Effects: leading and trailing silence trimmed, loudness-normalised,
96 kbps mono (audio/sfx/). Voice takes: cut at their N-1 longest silences (each line of the take is separated by
a [long pause]) into one clip per line, 64 kbps mono, named speaker-<hash of the exact words> (audio/vo/), the
same name js/voicekey.js computes, so changing a line falls back to silence until it is regenerated.
Music is not generated yet (the account ran out of credits): the game plays its Web Audio synth instead.
"""
import json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.normpath(os.path.join(HERE, '..', '..'))
RAW = sys.argv[1]
SFX_DIR, VO_DIR, MUSIC_DIR = (os.path.join(GAME, 'audio', d) for d in ('sfx', 'vo', 'music'))
for d in (SFX_DIR, VO_DIR, MUSIC_DIR): os.makedirs(d, exist_ok=True)

def run(*a): return subprocess.run(a, capture_output=True, text=True)

START_TRIM = 'silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.02'
TMP = tempfile.mkdtemp()

def encode(src, out, lufs, kbps, ss=None, to=None, cap=None):
    """Trim leading silence, normalise loudness, encode mono. Two ffmpeg passes: silenceremove and loudnorm in one
    filter chain made ffmpeg spin forever on one of the effects."""
    mid = os.path.join(TMP, 'mid.wav')
    a = ['ffmpeg', '-nostdin', '-y'] + (['-ss', f'{ss:.3f}', '-to', f'{to:.3f}'] if ss is not None else []) + ['-i', src, '-af', START_TRIM, '-ac', '1', mid]
    r = run(*a)
    if r.returncode: return r
    b = ['ffmpeg', '-nostdin', '-y', '-i', mid, '-af', f'loudnorm=I={lufs}:TP=-2:LRA=7'] + (['-t', str(cap)] if cap else []) + ['-ac', '1', '-b:a', f'{kbps}k', out]
    return run(*b)
sfx = []
for f in sorted(os.listdir(RAW)):
    if not f.endswith('.mp3') or f.startswith('take-'): continue
    name = f[:-4]
    out = os.path.join(SFX_DIR, name + '.mp3')
    r = encode(os.path.join(RAW, f), out, -18, 96, cap=3.5)
    if r.returncode: print('sfx failed', name, r.stderr[-300:]); continue
    sfx.append(name)

def fnv(s):
    h = 2166136261
    for ch in s.encode('utf-16-le')[::2] if False else [ord(c) for c in s]:
        h ^= ch; h = (h * 16777619) & 0xffffffff
    return h
def b36(n):
    d = '0123456789abcdefghijklmnopqrstuvwxyz'; s = ''
    while n: s = d[n % 36] + s; n //= 36
    return s or '0'
def key(who, text): return f'{who}-{b36(fnv(text.strip()))}'

voices = []
takes = json.load(open(os.path.join(HERE, 'takes.json')))
for t in takes:
    src = os.path.join(RAW, f"take-{t['speaker']}.mp3")
    if not os.path.exists(src): print('missing take', t['speaker']); continue
    n = len(t['lines'])
    r = run('ffmpeg', '-nostdin', '-i', src, '-af', 'silencedetect=noise=-38dB:d=0.28', '-f', 'null', '-')
    starts = [float(x) for x in re.findall(r'silence_start: ([\d.]+)', r.stderr)]
    ends = [(float(a), float(b)) for a, b in re.findall(r'silence_end: ([\d.]+) \| silence_duration: ([\d.]+)', r.stderr)]
    total = float(re.search(r'Duration: (\d+):(\d+):([\d.]+)', r.stderr).expand(r'\1 \2 \3').split()[0]) * 3600 if False else None
    dur = run('ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', src).stdout.strip()
    dur = float(dur)
    gaps = [(s, e) for s, (e, d) in zip(starts, ends)]   # (start of silence, end of silence)
    # drop the take's own leading/trailing silence, keep the n-1 longest inner pauses
    inner = [(s, e) for s, e in gaps if s > 0.3 and e < dur - 0.05]
    inner.sort(key=lambda g: g[0] - g[1])
    cuts = sorted(inner[:n - 1])
    if len(cuts) != n - 1: print(f"{t['speaker']}: found {len(cuts)} pauses, wanted {n - 1}"); continue
    bounds = [0.0] + [((s + e) / 2) for s, e in cuts] + [dur]
    for i, line in enumerate(t['lines']):
        a, b = bounds[i], bounds[i + 1]
        k = key(t['speaker'], line['text'])
        assert k == line['key'], (k, line['key'])
        out = os.path.join(VO_DIR, k + '.mp3')
        r = encode(src, out, -17, 64, ss=a, to=b)
        if r.returncode: print('clip failed', k, r.stderr[-200:]); continue
        voices.append(k)

music = sorted(f[:-4] for f in os.listdir(MUSIC_DIR) if f.endswith('.mp3'))
with open(os.path.join(GAME, 'js', 'audio-files.js'), 'w') as fh:
    fh.write('// Generated by dev/audio/process.py: the audio files that exist. Anything not listed falls back to the synth\n// (music, effects) or to silence (voices).\n')
    fh.write(f'export const MUSIC = {json.dumps(music)};\n')
    fh.write(f'export const SFX = {json.dumps(sorted(sfx))};\n')
    fh.write(f'export const VOICES = new Set({json.dumps(sorted(voices))});\n')
print(f'{len(sfx)} effects, {len(voices)} voice clips, {len(music)} music tracks')
