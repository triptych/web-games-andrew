export const GLYPHS = {};
for (const [ch, rows] of Object.entries(G)) {
    GLYPHS[ch] = rows.split('/').map((r) => [...r].map((c) => c === '#'));
}

export const CHAR_W = 6;   // 5 + 1 spacing
export const CHAR_H = 7;

export function glyph(ch) {
    return GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
}

export function textWidth(text, scale = 1) {
    return text.length ? (text.length * CHAR_W - 1) * scale : 0;
}

/**
 * Draw text into a 2D context whose origin is top-left. (x, y) is the top-left of the
 * first glyph unless align is 'center' / 'right'. A 1-px dark drop shadow keeps it
 * legible over the playfield.
 */
export function drawText(ctx, text, x, y, color, scale = 1, align = 'left', shadow = true) {
    text = String(text);
    const w = textWidth(text, scale);
    let x0 = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
    const y0 = Math.round(y);
    if (shadow) {
        ctx.fillStyle = 'rgba(0,0,0,0.85)';
        blit(ctx, text, x0 + scale, y0 + scale, scale);
    }
    ctx.fillStyle = color;
    blit(ctx, text, x0, y0, scale);
    return w;
}

function blit(ctx, text, x0, y0, s) {
    for (let i = 0; i < text.length; i++) {
        const g = glyph(text[i]);
        const gx = x0 + i * CHAR_W * s;
        for (let r = 0; r < 7; r++) {
            const row = g[r];
            let run = -1;
            for (let c = 0; c <= 5; c++) {
                const on = c < 5 && row[c];
                if (on && run < 0) run = c;
                else if (!on && run >= 0) { ctx.fillRect(gx + run * s, y0 + r * s, (c - run) * s, s); run = -1; }
            }
        }
    }
}
