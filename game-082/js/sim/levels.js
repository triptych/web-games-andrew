// The sectors of the Baron's station. Pure data and a builder; no rendering.
//
// Each map is 26 rows (0 the ceiling, 25 the floor). A row of 14 characters is the left half of
// the interior (columns 2–15) and is mirrored onto 16–29; a row of 28 characters is the whole
// interior. Columns 0–1 and 30–31 are always wall.
//   #  block (stand on top, jump up through it from below)
//   .  space
//   b blip  s spark  g glooper  r grunt  m comet moth  u saucer — an enemy's spawn; it stands on
//   the row below. Letters in a mirrored row spawn a mirrored pair.
// Platforms are four rows apart: the jump is 4.76 tiles. The floor and ceiling have the same
// gap in the middle, so anything that falls out of the bottom drops back in at the top.
//
// air:   the point bubbles drift to once they float (the "air current")
// hurry: seconds before HURRY UP!     zap / nova: seconds between special bubbles (0 = none)

