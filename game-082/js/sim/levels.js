export const LAST = LEVELS.length - 1;          // the boss
export const ENEMY_CODES = { b: 'blip', s: 'spark', g: 'glooper', r: 'grunt', m: 'moth', u: 'saucer' };

export function themeOf(idx) {
    if (LEVELS[idx]?.boss) return THEMES[5];
    return THEMES[Math.min(4, Math.floor(idx / 5))];
}

const cache = new Map();

/** The built sector: tiles (1 = block), enemy spawns and the level's settings. Cached; never mutate. */
export function buildLevel(idx) {
    if (cache.has(idx)) return cache.get(idx);
    const D = LEVELS[idx];
    if (!D) throw new Error('no level ' + idx);
    if (D.rows.length !== H) throw new Error(`level ${idx + 1}: ${D.rows.length} rows, want ${H}`);
    const tiles = new Array(W * H).fill(0);
    const spawns = [];
    D.rows.forEach((row, r) => {
        let full;
        if (row.length === 14) full = row + [...row].reverse().join('');
        else if (row.length === 28) full = row;
        else throw new Error(`level ${idx + 1} row ${r}: ${row.length} characters`);
        for (let i = 0; i < 28; i++) {
            const ch = full[i];
            if (ch === '#') tiles[r * W + 2 + i] = 1;
            else if (ch !== '.' && !ENEMY_CODES[ch]) throw new Error(`level ${idx + 1} row ${r}: '${ch}'`);
        }
        const src = row.length === 14 ? row : full;
        for (let i = 0; i < src.length; i++) {
            const type = ENEMY_CODES[src[i]];
            if (!type) continue;
            const x = 2 + i + 1;
            spawns.push({ type, x, y: r + 1 });
            if (row.length === 14) spawns.push({ type, x: W - x, y: r + 1 });
        }
    });
    for (let r = 0; r < H; r++) for (const c of [0, 1, W - 2, W - 1]) tiles[r * W + c] = 1;
    const L = {
        idx, name: D.name, tiles, spawns, boss: !!D.boss,
        air: { x: D.air[0], y: D.air[1] },
        hurry: D.hurry ?? 42, zap: D.zap ?? 0, nova: D.nova ?? 0,
        theme: themeOf(idx),
    };
    cache.set(idx, L);
    return L;
}
