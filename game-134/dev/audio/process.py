"""UFOops! audio pipeline: raw ElevenLabs downloads -> game-134/audio/ (needs ffmpeg).

    python3 -I game-134/dev/audio/process.py RAW_DIR

RAW_DIR holds music-*.mp3, sfx-*.mp3 and vo-*.mp3 as downloaded. Music is loudness-normalised with a short
fade at the loop seam; effects are trimmed of silence; each voice take is cut into its lines at its longest
pauses (ffmpeg silencedetect) or at transcript-derived times (CUTS), checked against the line lengths in dev/audio/lines.json, and named after
the line ids. Writes js/voicelines.js (line text -> file) for the game.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GAME = HERE.parent.parent
OUT = GAME / 'audio'
LINES = json.loads((HERE / 'lines.json').read_text())
TAKES = {'vo-mother-brief': 'mother-brief', 'vo-mother-grade': 'mother-grade', 'vo-mother-radio': 'mother-radio', 'vo-zib': 'zib', 'vo-general': 'general'}


def ff(*args):
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', *args], check=True)


def duration(path):
    out = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(path)], capture_output=True, text=True).stdout
    return float(out.strip())


def silences(path, noise='-38dB', d=0.3):
    err = subprocess.run(['ffmpeg', '-hide_banner', '-i', str(path), '-af', f'silencedetect=noise={noise}:d={d}', '-f', 'null', '-'], capture_output=True, text=True).stderr
    starts = [float(x) for x in re.findall(r'silence_start: ([0-9.]+)', err)]
    ends = [float(x) for x in re.findall(r'silence_end: ([0-9.]+)', err)]
    return list(zip(starts, ends))


# Cut times for the two takes that pause inside lines too ("Good. Not great. Good.", "...believes in you.
# [dryly] Mostly."). Taken from ElevenLabs speech-to-text word timings of each take: the middle of every
# "[long pause]" the transcript marks. A length-fitting split picked a wrong pause in both takes.
CUTS = {
    'vo-mother-brief': [7.16, 14.98, 21.95, 28.53, 34.44, 42.78, 49.27],
    'vo-mother-grade': [3.84, 8.73, 12.62, 16.06, 20.47, 23.32, 28.69, 31.15, 34.62, 37.76, 41.41, 45.13],
}


def main(raw):
    raw = Path(raw)
    for sub in ('music', 'sfx', 'vo'):
        (OUT / sub).mkdir(parents=True, exist_ok=True)
    # music: normalise, fade the last 0.6 s and the first 0.05 s so the loop seam doesn't click
    for f in sorted(raw.glob('music-*.mp3')):
        d = duration(f)
        ff('-i', str(f), '-af', f'loudnorm=I=-16:TP=-1.5,afade=t=in:d=0.05,afade=t=out:st={d - 0.6:.2f}:d=0.6',
           '-ac', '2', '-b:a', '80k', str(OUT / 'music' / (f.stem.replace('music-', '') + '.mp3')))
        print('music', f.stem, round(d, 1))
    # effects: trim leading/trailing silence, normalise, mono
    for f in sorted(raw.glob('sfx-*.mp3')):
        name = f.stem.replace('sfx-', '')
        trim = '' if name == 'beam' else 'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,'
        ff('-i', str(f), '-af', f'{trim}loudnorm=I=-14:TP=-1', '-ac', '1', '-b:a', '96k', str(OUT / 'sfx' / f'{name}.mp3'))
    print('sfx', len(list(raw.glob('sfx-*.mp3'))))
    # voices: cut each take at its N-1 longest pauses
    table = {}
    for stem, key in TAKES.items():
        f = raw / f'{stem}.mp3'
        lines = LINES[key]
        sil = silences(f)
        if len(sil) < len(lines) - 1:
            print('NOT ENOUGH PAUSES in', stem, len(sil), 'for', len(lines)); continue
        total = duration(f)
        total_chars = sum(len(l['text']) for l in lines)
        if stem in CUTS:
            cuts = CUTS[stem]
        else:   # one pause per gap: the longest ones are the gaps
            cuts = sorted((a + b) / 2 for a, b in sorted(sil, key=lambda s: s[1] - s[0], reverse=True)[:len(lines) - 1])
        bounds = [0.0, *cuts, total]
        for i, line in enumerate(lines):
            a, b = bounds[i], bounds[i + 1]
            out = OUT / 'vo' / f"{key}-{line['id']}.mp3"
            ff('-i', str(f), '-ss', f'{a:.3f}', '-to', f'{b:.3f}', '-af',
               'silenceremove=start_periods=1:start_threshold=-42dB,areverse,silenceremove=start_periods=1:start_threshold=-42dB,areverse,loudnorm=I=-15:TP=-1',
               '-ac', '1', '-b:a', '64k', str(out))
            # sanity: clip length against its share of the text
            expect = total * len(line['text']) / total_chars
            flag = '  <-- check' if not (0.45 < (b - a) / max(expect, 0.3) < 2.2) else ''
            print(f"  {key}-{line['id']}: {b - a:5.2f}s (expected ~{expect:4.1f}s) {line['text'][:50]}{flag}")
            table[line['text']] = f"{key}-{line['id']}"
    js = '// Generated by dev/audio/process.py: what each spoken line is called in audio/vo/.\n'
    js += '// Keys are the exact text the game shows; the speaker is the file name prefix.\n'
    js += 'export const VOICE = ' + json.dumps(table, indent=1, ensure_ascii=False) + ';\n'
    (GAME / 'js' / 'voicelines.js').write_text(js)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'raw')
