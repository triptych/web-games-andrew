/** char -> Uint8Array of GLYPH_H rows, each a 5-bit mask (bit 4 = leftmost) */
const compiled = new Map();
for (const [ch, art] of Object.entries(GLYPHS)) {
    const rows = art.split('/');
    const bits = new Uint8Array(GLYPH_H);
    for (let y = 0; y < GLYPH_H; y++) {
        const row = rows[y] || '.....';
        let m = 0;
        for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') m |= 1 << (GLYPH_W - 1 - x);
        bits[y] = m;
    }
    compiled.set(ch, bits);
}

export const CHAR_W = GLYPH_W + 1;   // one column of letter spacing
export const CHAR_H = GLYPH_H;
export const LINE_H = GLYPH_H + 2;

export function textWidth(str) {
    return str.length * CHAR_W - 1;
}

/**
 * Draw a string. `shadow` (a palette index) draws the same glyph offset by
 * one pixel first, which is how DOS games kept text readable over a busy
 * 3D view.
 */
export function drawText(fb, x, y, str, color, shadow = null) {
    str = String(str).toUpperCase();
    if (shadow !== null) drawText(fb, x + 1, y + 1, str, shadow, null);
    let cx = x;
    for (const ch of str) {
        const bits = compiled.get(ch);
        if (bits) {
            for (let gy = 0; gy < GLYPH_H; gy++) {
                const m = bits[gy];
                if (!m) continue;
                for (let gx = 0; gx < GLYPH_W; gx++) {
                    if (m & (1 << (GLYPH_W - 1 - gx))) fb.pset(cx + gx, y + gy, color);
                }
            }
        }
        cx += CHAR_W;
    }
    return cx;
}

export function drawTextCentered(fb, cx, y, str, color, shadow = null) {
    drawText(fb, cx - (textWidth(str) >> 1), y, str, color, shadow);
}

/** Greedy word wrap to a pixel width, returns an array of lines. */
export function wrapText(str, maxPixels) {
    const words = String(str).split(/\s+/);
    const lines = [];
    let line = '';
    for (const w of words) {
        const candidate = line ? line + ' ' + w : w;
        if (textWidth(candidate) > maxPixels && line) {
            lines.push(line);
            line = w;
        } else {
            line = candidate;
        }
    }
    if (line) lines.push(line);
    return lines;
}
