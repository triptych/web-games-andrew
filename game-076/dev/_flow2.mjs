import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1366, height: 860 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.stack || e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await p.route('https://fonts.googleapis.com/**', (r) => r.fulfill({ status: 200, contentType: 'text/css', body: '' }));
await p.goto('http://127.0.0.1:8076/game-076/index.html');
await p.evaluate(() => localStorage.clear()); await p.reload();
await p.waitForFunction(() => window.__tal);
await p.locator('.modecard').nth(1).click();
await p.waitForSelector('.scene'); await p.click('.scskip');
await p.evaluate(() => __tal.openSample());
await p.waitForTimeout(500);
await p.screenshot({ path: 'game-076/dev/shots/sample-editor.png' });
await p.evaluate(() => { const m = __tal.curMap(); const ev = m.events.find(e => e.name === 'Old Tree'); __tal.view().sel = ev.id; document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' })); });
await p.waitForTimeout(500);
await p.screenshot({ path: 'game-076/dev/shots/eventeditor.png' });
await p.keyboard.press('Escape');
await p.evaluate(() => document.getElementById('btn-db').click());
await p.waitForTimeout(300);
await p.locator('.tab', { hasText: 'Enemies' }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: 'game-076/dev/shots/database.png' });
await p.locator('.tab', { hasText: 'System' }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: 'game-076/dev/shots/system.png' });
if (errs.length) console.log('ERRORS:\n' + errs.join('\n'));
await b.close();
