#!/usr/bin/env python3
"""Where each portrait's face is, for the round portraits (friends list, places, Starfall). Needs Pillow and numpy.

    python3 -I game-127/dev/art/faces.py [SHEET.png]

Portraits are full figures trimmed to the figure, so their widths differ (300-590 px at 960 tall) and one zoom by
width lands on a different part of each. This finds the head (the top of the figure; across, the middle of the opaque
pixels a little below it), takes a square a fifth of the height around it, applies the hand checks in OVERRIDES
(wings, staffs, hats, tall hair and children's bigger heads), and writes js/faces.js. With SHEET, it also draws every
crop as a circle on one sheet, to check by eye after new portraits.
"""
import glob, json, os, sys
import numpy as np
from PIL import Image, ImageDraw

GAME = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))

# s: square side as a share of the height (.2); dy: face centre below the figure's top (.1); dx: shift across.
OVERRIDES = {
    'cael-adult-angry': {'dx': .035}, 'cael-adult-sad': {'dx': .022}, 'cael-adult-neutral': {'dx': .01}, 'cael-adult-happy': {'dx': .008},
    **{f'cael-child-{m}': {'s': .23, 'dy': .11} for m in ('angry', 'happy', 'neutral', 'sad')},
    'velis': {'dx': -.055}, 'rowan-adult-happy': {'dx': .025}, 'rowan-child': {'s': .22, 'dx': -.01}, 'theo-adult': {'dx': .015},
    'coralie': {'dy': .16, 'dx': -.01}, 'pip-child': {'dy': .17, 's': .22},
    'lumi-child': {'s': .24, 'dy': .13}, 'lumi-adult': {'dy': .11}, 'lumi-adult-happy': {'dy': .11},
}


def main():
    sheet = sys.argv[1] if len(sys.argv) > 1 else None
    out, crops = {}, []
    for p in sorted(glob.glob(os.path.join(GAME, 'art', 'por', '*.webp'))):
        k = os.path.basename(p)[:-5]
        im = Image.open(p).convert('RGBA')
        a = np.asarray(im)[..., 3] > 128
        H, W = a.shape
        top = int(np.where(a.sum(1) > 3)[0][0])
        o = OVERRIDES.get(k, {})
        cx = np.where(a[top + int(.03 * H): top + int(.11 * H)].any(0))[0].mean() + o.get('dx', 0) * H
        cy = top + o.get('dy', .1) * H
        s = o.get('s', .2) * H
        # In units of the circle's size: the image's offset (x, y) and width.
        out[k] = [round(.5 - cx / s, 3), round(.5 - cy / s, 3), round(W / s, 3)]
        if sheet:
            c = Image.new('RGBA', (int(s), int(s)), (42, 21, 32, 255))
            c.alpha_composite(im, (int(s / 2 - cx), int(s / 2 - cy)))
            crops.append((k, c.resize((110, 110))))
    body = ',\n'.join(f"    '{k}': [{v[0]}, {v[1]}, {v[2]}]" for k, v in out.items())
    with open(os.path.join(GAME, 'js', 'faces.js'), 'w') as f:
        f.write('// Generated by dev/art/faces.py: where each portrait\'s face is, as [x, y, width] in units of the\n'
                '// round portrait\'s size (the image\'s offset and its width when the face fills the circle).\n'
                f'export const FACES = {{\n{body},\n}};\n')
    if sheet:
        m = Image.new('L', (110, 110), 0); ImageDraw.Draw(m).ellipse((0, 0, 109, 109), 255)
        img = Image.new('RGB', (1200, ((len(crops) + 9) // 10) * 132), (20, 10, 16)); d = ImageDraw.Draw(img)
        for i, (k, c) in enumerate(crops):
            x, y = (i % 10) * 120 + 5, (i // 10) * 132 + 2
            img.paste(c.convert('RGB'), (x, y), m); d.text((x, y + 112), k[:18], fill=(230, 200, 210))
        img.save(sheet)
    print(f'{len(out)} faces -> js/faces.js')


if __name__ == '__main__':
    main()
